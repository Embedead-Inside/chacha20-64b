int main(void) {
    uint8_t key[32]; for (int i = 0; i < 32; i++) key[i] = (uint8_t)i;
    chacha20_64b_ctx_t ctx; uint8_t buf[64];

    /* RFC 8439 2.3.2 ブロック関数（ゼロ平文 = キーストリーム） */
    static const uint8_t n1[12] = {0,0,0,9,0,0,0,0x4a,0,0,0,0};
    chacha20_64b_init(&ctx, key, n1);
    memset(buf, 0, 64); chacha20_64b_transform(buf, &ctx, 1);
    CHECK(memcmp(buf, KS232, 64) == 0, "RFC8439 2.3.2 block function");

    /* RFC 8439 2.4.2 暗号化（114B = 64B + 50B。2ブロック目は部分利用） */
    static const uint8_t n2[12] = {0,0,0,0,0,0,0,0x4a,0,0,0,0};
    const char *pt = "Ladies and Gentlemen of the class of '99: If I could offer you only one tip for the future, sunscreen would be it.";
    uint8_t msg[128]; memset(msg, 0, sizeof msg); memcpy(msg, pt, 114);
    chacha20_64b_init(&ctx, key, n2);
    chacha20_64b_transform(msg, &ctx, 1);
    chacha20_64b_transform(msg + 64, &ctx, 2);
    CHECK(memcmp(msg, CT242, 114) == 0, "RFC8439 2.4.2 encryption (2 blocks)");

    /* 参照実装(Python cryptography)との照合: counter=0 と 0xFFFFFFFF */
    chacha20_64b_init(&ctx, KEY2, N3);
    memset(buf, 0, 64); chacha20_64b_transform(buf, &ctx, 0);
    CHECK(memcmp(buf, KS3_0, 64) == 0, "reference keystream, counter=0");
    memset(buf, 0, 64); chacha20_64b_transform(buf, &ctx, 0xFFFFFFFFu);
    CHECK(memcmp(buf, KS3_FFFFFFFF, 64) == 0, "reference keystream, counter=0xFFFFFFFF");

    /* アラインメント非依存: オフセット 0..7 で同じ結果になること */
    int ok = 1;
    for (int off = 0; off < 8; off++) {
        uint8_t raw[80]; memset(raw, 0, sizeof raw);
        chacha20_64b_transform(raw + off, &ctx, 0);
        if (memcmp(raw + off, KS3_0, 64) != 0) ok = 0;
    }
    CHECK(ok, "unaligned buffers (offset 0..7)");

    /* 往復: 暗号化 → 同一関数で復号 → 元に戻る */
    uint8_t orig[64], work[64];
    for (int i = 0; i < 64; i++) orig[i] = (uint8_t)(i * 31 + 7);
    memcpy(work, orig, 64);
    chacha20_64b_transform(work, &ctx, 5);
    CHECK(memcmp(work, orig, 64) != 0, "ciphertext differs from plaintext");
    chacha20_64b_transform(work, &ctx, 5);
    CHECK(memcmp(work, orig, 64) == 0, "round trip in place");

    /* wipe */
    chacha20_64b_wipe(&ctx);
    ok = 1; for (int i = 0; i < 16; i++) if (ctx.state[i]) ok = 0;
    CHECK(ok, "wipe clears state");

    printf(fails ? "\n%d test(s) FAILED\n" : "\nall tests passed\n", fails);
    return fails != 0;
}
