static const uint8_t KEY2[32] = {0x03,0x0a,0x11,0x18,0x1f,0x26,0x2d,0x34,0x3b,0x42,0x49,0x50,0x57,0x5e,0x65,0x6c,0x73,0x7a,0x81,0x88,0x8f,0x96,0x9d,0xa4,0xab,0xb2,0xb9,0xc0,0xc7,0xce,0xd5,0xdc};
